import { test } from 'node:test';
import assert from 'node:assert/strict';
import { tokenize, matchesPrefix, renderRules, RULES_PATH } from '../lib/codex-rules.mjs';

test('tokenize respects quotes and stops at operators', () => {
  assert.deepEqual(tokenize('git push --force origin main'), ['git', 'push', '--force', 'origin', 'main']);
  assert.deepEqual(tokenize('echo "git push --force"'), ['echo', 'git push --force']);
  assert.deepEqual(tokenize("echo 'a b' && git push"), ['echo', 'a b']);
  assert.deepEqual(tokenize('ls | wc; x'), ['ls']);
});

test('matchesPrefix', () => {
  const p = [['git', 'push', '--force']];
  assert.equal(matchesPrefix('git push --force origin main', p), true);
  assert.equal(matchesPrefix('git push origin +main', p), false);
  assert.equal(matchesPrefix('echo "git push --force"', p), false);
  assert.equal(matchesPrefix('git push --force', []), false);
});

test('renderRules', () => {
  const out = renderRules([
    { pattern: 'x', reason: 'Force push cần người dùng xác nhận.', prefixes: [['git', 'push', '--force'], ['git', 'push', '-f']] },
    { pattern: 'y', reason: 'no prefixes' },
  ]);
  assert.match(out, /^# Generated by ai-native-sdlc from sdlc\/config\.json gates\. Do not edit\./);
  assert.equal(out.split('\n').filter((l) => l.startsWith('prefix_rule(')).length, 2);
  assert.ok(out.includes('prefix_rule(pattern=["git", "push", "--force"], decision="prompt", justification="Force push cần người dùng xác nhận.")'));
  assert.ok(!out.includes('no prefixes'));
  assert.equal(RULES_PATH, '.codex/rules/ai-native-sdlc.rules');
});
