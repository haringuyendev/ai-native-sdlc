// Helpers to mirror config gates as Codex execpolicy rules (Codex PreToolUse cannot "ask").

export const RULES_PATH = '.codex/rules/ai-native-sdlc.rules';

// Split a shell command into words, honouring quotes; stop at the first &&, ;, |.
export function tokenize(command) {
  const tokens = [];
  let cur = '';
  let has = false;
  let quote = null;
  const push = () => {
    if (has) tokens.push(cur);
    cur = '';
    has = false;
  };
  for (const ch of String(command ?? '')) {
    if (quote) {
      if (ch === quote) quote = null;
      else cur += ch;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
      has = true;
    } else if (/\s/.test(ch)) {
      push();
    } else if (ch === ';' || ch === '|' || (ch === '&' && cur.endsWith('&'))) {
      if (ch === '&') {
        cur = cur.slice(0, -1);
        if (cur === '') has = false;
      }
      push();
      return tokens;
    } else {
      cur += ch;
      has = true;
    }
  }
  push();
  return tokens;
}

export function matchesPrefix(command, prefixes) {
  const t = tokenize(command);
  return (prefixes ?? []).some((p) => p.length > 0 && p.length <= t.length && p.every((w, i) => t[i] === w));
}

export function renderRules(gates) {
  const lines = ['# Generated by ai-native-sdlc from sdlc/config.json gates. Do not edit.'];
  for (const g of gates ?? []) {
    for (const p of g.prefixes ?? []) {
      lines.push(`prefix_rule(pattern=${JSON.stringify(p).replace(/","/g, '", "')}, decision="prompt", justification=${JSON.stringify(g.reason ?? '')})`);
    }
  }
  return `${lines.join('\n')}\n`;
}
